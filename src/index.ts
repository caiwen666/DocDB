import { app, BrowserWindow, ipcMain } from "electron";
import { getFileDetail } from "./utils/backend";
import { Global } from "./config/backend";
import {
	addDocument,
	deleteDocument,
	getDocument,
	getRemoteVersion,
	getTrack,
	initDatabase,
	isFileExist,
	pullDatabase,
	pushDatabase,
	searchDocument,
	updateDocument,
} from "./config/Database";
import { Database } from "./config/Database";
import { loadConfig } from "./config/settings";
import { InitAPI } from "./api/backend";
import * as fs from "node:fs";
import path from "path";
// This allows TypeScript to pick up the magic constants that's auto-generated by Forge's Webpack
// plugin that tells the Electron app where to look for the Webpack-bundled app code (depending on
// whether you're running in development or production).
declare const MAIN_WINDOW_WEBPACK_ENTRY: string;
declare const MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY: string;

// Handle creating/removing shortcuts on Windows when installing/uninstalling.
if (require("electron-squirrel-startup")) {
	app.quit();
}

const createWindow = (): void => {
	// Create the browser window.
	const mainWindow = new BrowserWindow({
		frame: false,
		height: 600,
		width: 800,
		minHeight: 600,
		minWidth: 800,
		show: false,
		webPreferences: {
			preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
			nodeIntegration: true,
		},
	});

	ipcMain.on("maximize", (event) => {
		const window = BrowserWindow.fromWebContents(event.sender);
		if (window.isMaximized()) {
			window.unmaximize();
		} else {
			window.maximize();
		}
	});

	ipcMain.on("minimize", (event) => {
		const window = BrowserWindow.fromWebContents(event.sender);
		window.minimize();
	});

	ipcMain.on("close", (event) => {
		const window = BrowserWindow.fromWebContents(event.sender);
		window.close();
	});

	// and load the index.html of the app.
	mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);

	mainWindow.once("ready-to-show", () => {
		mainWindow.show();
	});

	mainWindow.on("maximize", () => {
		mainWindow.webContents.send("window-state-change", true);
	});

	mainWindow.on("unmaximize", () => {
		mainWindow.webContents.send("window-state-change", false);
	});

	// Open the DevTools.
	mainWindow.webContents.openDevTools({ mode: "detach" });

	Global.window = mainWindow;
	// 读入字体
	Global.font = fs.readFileSync(path.join(process.cwd(), "font.ttf"));
	// 清理临时文件
	const tempFiles = fs.readdirSync(path.join(process.cwd(), "data", "tmp"));
	for (const file of tempFiles) {
		try {
			fs.rmSync(path.join(process.cwd(), "data", "tmp", file), {
				force: true,
			});
		} catch (e) {
			console.error(`delete ${file} failed`, e);
		}
	}
	initDatabase();
	loadConfig();
};

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on("ready", createWindow);

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on("window-all-closed", () => {
	if (process.platform !== "darwin") {
		app.quit();
	}
});

app.on("activate", () => {
	// On OS X it's common to re-create a window in the app when the
	// dock icon is clicked and there are no other windows open.
	if (BrowserWindow.getAllWindows().length === 0) {
		createWindow();
	}
});

InitAPI();
ipcMain.handle("getFileDetail", (_, path) => getFileDetail(path));
ipcMain.handle("getDatabaseStatus", () => Database.status);
ipcMain.handle("getDatabaseVersion", () => Database.version);
ipcMain.handle("isFileExist", (_, md5) => isFileExist(md5));
ipcMain.handle("addDocument", (_, docs) => addDocument(docs));
ipcMain.handle("deleteDocument", (_, id) => deleteDocument(id));
ipcMain.handle("updateDocument", (_, id, info) => updateDocument(id, info));
ipcMain.handle("getDocument", (_, id) => getDocument(id));
ipcMain.handle("searchDocument", (_, keyword) => searchDocument(keyword));
ipcMain.handle("pushDatabase", () => pushDatabase());
ipcMain.handle("pullDatabase", () => pullDatabase());
ipcMain.handle("getTrack", () => getTrack());
ipcMain.handle("getRemoteVersion", () => getRemoteVersion());
